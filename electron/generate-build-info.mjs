import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = join(__dirname, "..", "src", "ui", "build-info.ts");

// A visible, human-checkable "which build am I actually running" marker (Phase 1 testing
// friction has repeatedly come down to "is this really the latest code?" — this settles that
// question at a glance in the app itself, instead of guessing from file timestamps).
const builtAt = new Date().toISOString();

writeFileSync(
  outFile,
  `// Auto-generated by electron/generate-build-info.mjs on every "npm run build" — do not edit.\n` +
    `export const BUILT_AT = ${JSON.stringify(builtAt)};\n`
);

console.log(`Wrote build stamp: ${builtAt}`);
